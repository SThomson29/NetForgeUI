"""
Generate's section tick-boxes come from the NetForge generate role's task
tags, so a template added there can be generated by itself with no change
here.
"""

import os

import pytest
import yaml

from app import sections
from app.project import create_project
from app.utils import add_project_hosts, ensure_workspace

ROLE = """
- name: Ensure output directory exists
  ansible.builtin.file: {path: x, state: directory}
  tags: always

- name: Render | Management
  ansible.builtin.template: {src: CX_management.j2, dest: x}
  tags: [full, management]

- name: Render | VRFs
  ansible.builtin.template: {src: CX_vrfs.j2, dest: x}
  tags: [full, vrfs, routing]

- name: Render | Interfaces - Physical
  ansible.builtin.template: {src: a.j2, dest: x}
  tags: [full, interfaces_physical, interfaces]

- name: Render | Interfaces - LAG
  ansible.builtin.template: {src: b.j2, dest: x}
  tags: [full, interfaces_lag, interfaces]

- name: Render | OSPF
  ansible.builtin.template: {src: CX_ospf.j2, dest: x}
  tags: [full, ospf, routing]

- name: Render | Spanning Tree
  ansible.builtin.template: {src: CX_stp.j2, dest: x}
  tags: [full, spanning_tree]

- name: Assemble configuration file
  ansible.builtin.assemble: {src: x, dest: y}
  tags: always
"""


def parsed(text=ROLE):
    return sections.from_tasks(yaml.safe_load(text))


def tags(found):
    return [s['tag'] for s in found]


class TestFromTasks:

    def test_sections_in_role_order_with_shared_tags_after_their_last(self):
        assert tags(parsed()) == ['management', 'vrfs', 'interfaces_physical',
                                  'interfaces_lag', 'interfaces', 'ospf', 'routing',
                                  'spanning_tree']

    def test_known_sections_keep_their_wording(self):
        by = {s['tag']: s for s in parsed()}
        assert by['interfaces_lag']['label'] == 'LAG interfaces'
        assert by['interfaces']['label'] == 'All interfaces'

    def test_a_new_template_is_named_from_its_task(self):
        by = {s['tag']: s for s in parsed()}
        assert by['spanning_tree'] == {'tag': 'spanning_tree', 'label': 'Spanning Tree',
                                       'covers': []}

    def test_a_shared_tag_says_what_it_covers(self):
        by = {s['tag']: s for s in parsed()}
        assert by['routing']['covers'] == ['VRFs', 'OSPF']
        assert by['interfaces']['covers'] == ['Physical interfaces', 'LAG interfaces']

    def test_full_and_always_are_not_offered(self):
        assert not {'full', 'always'} & set(tags(parsed()))

    def test_tags_as_a_string_and_tasks_inside_blocks(self):
        found = parsed("""
- name: Group
  block:
    - name: Render | QoS
      template: {src: q.j2, dest: x}
      tags: full, qos
""")
        assert found == [{'tag': 'qos', 'label': 'QoS', 'covers': []}]

    def test_a_task_without_the_render_prefix_is_named_from_its_tag(self):
        found = parsed("- name: port security\n  template: {src: p.j2, dest: x}\n"
                       "  tags: [full, port_security]\n")
        assert found[0]['label'] == 'Port security'

    def test_tags_that_are_not_plain_names_are_dropped(self):
        found = parsed("- name: Render | X\n  template: {src: p.j2, dest: x}\n"
                       "  tags: [full, 'bad tag', '<script>', ok_one]\n")
        assert tags(found) == ['ok_one']

    @pytest.mark.parametrize('text', ['', '[]', 'just: a mapping', '- not a task\n- 5\n',
                                      '- name: no tags\n  template: {src: a, dest: b}\n'])
    def test_nothing_usable_gives_nothing(self, text):
        assert parsed(text) == []


class TestSections:

    def write(self, app, text):
        path = os.path.join(app.config['ROLES_PATH'], sections.TASKS_FILE)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w') as f:
            f.write(text)

    def test_reads_the_role(self, app):
        self.write(app, ROLE)
        assert 'spanning_tree' in tags(sections.sections(app))

    def test_falls_back_when_the_role_is_missing(self, app):
        assert sections.sections(app) == sections.FALLBACK

    @pytest.mark.parametrize('text', ['{ not: [yaml', '- name: nothing tagged\n  debug: {msg: x}\n'])
    def test_falls_back_when_the_role_is_unusable(self, app, text):
        self.write(app, text)
        assert sections.sections(app) == sections.FALLBACK

    def test_fallback_covers_what_the_page_always_offered(self):
        assert {'staticroutes', 'interfaces', 'routing', 'vxlan', 'vsx', 'vsf', 'syslog',
                'sflow'} <= set(tags(sections.FALLBACK))

    def test_generate_page_offers_the_roles_sections(self, app, auth_client, skeleton_dir):
        ensure_workspace(app, 'admin')
        create_project(app, 'admin', 'p')
        add_project_hosts(app, 'admin', 'p', ['SW1'], 'none')
        self.write(app, ROLE)
        body = auth_client.get('/projects/admin/p/generate').get_data(as_text=True)
        assert 'value="spanning_tree" style="width:auto"> Spanning Tree' in body
        assert 'value="routing"' in body and '(VRFs + OSPF)' in body
        assert 'value="vxlan"' not in body      # not in this role, so not offered
