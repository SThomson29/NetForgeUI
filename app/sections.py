"""
The sections Generate can render on their own, read from NetForge.

Each "Render | ..." task in the generate role carries tags: its own, and
sometimes a shared one that selects several sections at once (interfaces,
routing). Reading them from the role, rather than listing them here, means
a template added to NetForge can be generated by itself as soon as the
repo is pulled, with no change to this app.

    sections(app) -> [{'tag', 'label', 'covers'}]

covers is empty for a single section, and lists the sections' labels for a
tag that selects several. Sections come in the role's own order; a tag that
selects several follows the last of them.

If the role can't be read (not cloned yet, or laid out differently), the
list this app shipped with is offered instead, so the page always works.
"""

import os
import re

import yaml

TASKS_FILE = os.path.join('generate_config', 'tasks', 'main.yml')

# Tags that aren't a choice of section: 'full' means everything and
# 'always' marks the assembly steps.
_NOT_SECTIONS = {'full', 'always', 'never', 'all', 'untagged', 'tagged'}

_TAG = re.compile(r'^[A-Za-z0-9_]{1,40}$')

# Wording for the sections this app knows. Anything else is named from its
# task ("Render | Spanning Tree" -> "Spanning Tree").
LABELS = {
    'staticroutes': 'Static routes', 'management': 'Management', 'general': 'General',
    'snmp': 'SNMP', 'aaa': 'AAA', 'banner': 'Banner', 'vrfs': 'VRFs', 'vlans': 'VLANs',
    'interface_groups': 'Interface groups',
    'interfaces_physical': 'Physical interfaces', 'interfaces_lag': 'LAG interfaces',
    'interfaces_loopback': 'Loopback interfaces', 'interfaces_vlan': 'VLAN interfaces',
    'ospf': 'OSPF', 'ibgp': 'iBGP', 'vxlan': 'VXLAN', 'vsx': 'VSX', 'vsf': 'VSF',
    'syslog': 'Syslog', 'sflow': 'sFlow',
    'interfaces': 'All interfaces', 'routing': 'Routing',
}

# What Generate offered before it read the role.
FALLBACK = [
    {'tag': t, 'label': label, 'covers': covers} for t, label, covers in [
        ('staticroutes', 'Static routes', []), ('management', 'Management', []),
        ('general', 'General', []), ('snmp', 'SNMP', []), ('aaa', 'AAA', []),
        ('banner', 'Banner', []), ('vrfs', 'VRFs', []), ('vlans', 'VLANs', []),
        ('interfaces_physical', 'Physical interfaces', []),
        ('interfaces_lag', 'LAG interfaces', []),
        ('interfaces_loopback', 'Loopback interfaces', []),
        ('interfaces_vlan', 'VLAN interfaces', []),
        ('interfaces', 'All interfaces', ['Physical interfaces', 'LAG interfaces',
                                          'Loopback interfaces', 'VLAN interfaces']),
        ('ospf', 'OSPF', []), ('ibgp', 'iBGP', []),
        ('routing', 'Routing', ['VRFs', 'OSPF', 'iBGP']),
        ('vxlan', 'VXLAN', []), ('vsx', 'VSX', []), ('vsf', 'VSF', []),
        ('syslog', 'Syslog', []), ('sflow', 'sFlow', []),
    ]
]


def _tasks(node):
    """Every task in a tasks file, including those inside blocks."""
    for task in node if isinstance(node, list) else []:
        if not isinstance(task, dict):
            continue
        yield task
        for key in ('block', 'rescue', 'always'):
            yield from _tasks(task.get(key))


def _tags(task):
    tags = task.get('tags')
    if isinstance(tags, str):
        tags = [t.strip() for t in tags.split(',')]
    return [str(t) for t in (tags or []) if _TAG.match(str(t)) and str(t) not in _NOT_SECTIONS]


def _task_label(task, tag):
    name = str(task.get('name') or '')
    if '|' in name:
        text = name.split('|', 1)[1].strip()
        if text:
            return text[:60]
    return tag.replace('_', ' ').capitalize()


def from_tasks(tasks):
    """The section list for a parsed tasks file. [] if it has no tagged
    render tasks."""
    renders = [(t, _tags(t)) for t in _tasks(tasks) if 'ansible.builtin.template' in t
               or 'template' in t]
    uses = {}                       # tag -> indexes of the tasks carrying it
    for i, (_task, tags) in enumerate(renders):
        for tag in tags:
            uses.setdefault(tag, []).append(i)

    # A task's own tag is one no other task carries; where every tag is
    # shared, the first stands for it.
    own = {}                        # task index -> its section tag
    for i, (_task, tags) in enumerate(renders):
        single = [t for t in tags if len(uses[t]) == 1]
        if single:
            own[i] = single[0]
    label = {i: LABELS.get(tag) or _task_label(renders[i][0], tag) for i, tag in own.items()}

    out, placed = [], set()
    for i in range(len(renders)):
        if i in own:
            out.append({'tag': own[i], 'label': label[i], 'covers': []})
        # A shared tag goes after the last section it selects.
        for tag in renders[i][1]:
            if len(uses[tag]) > 1 and uses[tag][-1] == i and tag not in placed:
                placed.add(tag)
                out.append({'tag': tag,
                            'label': LABELS.get(tag) or tag.replace('_', ' ').capitalize(),
                            'covers': [label[j] for j in uses[tag] if j in label]})
    return out


def sections(app):
    path = os.path.join(app.config.get('ROLES_PATH') or '', TASKS_FILE)
    try:
        with open(path, encoding='utf-8') as f:
            found = from_tasks(yaml.safe_load(f))
    except (OSError, yaml.YAMLError):
        found = []
    return found or FALLBACK
